bool Coin::flip_Coin(){
    double result = dis(gen);
    return chance_heads > result;
}
int Coin::flip_Sequence(int flips){
    int num_heads = 0;
    for(int i = 0; i < flips; i++){
        bool result = flip_Coin();
        if(result) num_heads++;
    }
    return num_heads;
}
double Coin::get_chance_heads() const{
    return chance_heads;
}

